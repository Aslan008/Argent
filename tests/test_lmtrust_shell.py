class TestL2L4ExecutionGuards:
    def test_run_text_replaces_undecodable_bytes_without_crashing(self):
        """run_text must not crash when subprocess emits invalid UTF-8 bytes."""
        res = run_text(
            ["python", "-c", "import sys; sys.stdout.buffer.write(b'hello \\xff world\\n')"],
            capture_output=True,
        )
        assert res.returncode == 0
        assert "hello" in res.stdout
        assert "world" in res.stdout

    def test_run_text_sets_stdin_devnull_for_captured_processes(self, monkeypatch):
        """Processes captured without explicit input must get stdin=DEVNULL to prevent hanging."""
        captured_kwargs = {}

        class FakePopen:
            def __init__(self, *args, **kwargs):
                captured_kwargs.update(kwargs)
                self.args = args
                self.returncode = 0
            def __enter__(self): return self
            def __exit__(self, *a): pass
            def communicate(self, *a, **k): return ("out", "err")

        monkeypatch.setattr(subprocess, "Popen", FakePopen)
        run_text(["dummy_cmd"], capture_output=True, timeout=10)
        assert captured_kwargs.get("stdin") == subprocess.DEVNULL

    def test_run_text_timeout_kills_tree_and_raises(self, monkeypatch):
        kill_tree_called = []
        monkeypatch.setattr("src.agent.shell.kill_process_tree", lambda proc: kill_tree_called.append(proc))

        class TimeoutPopen:
            def __init__(self, *args, **kwargs):
                self.args = args
                self.pid = 9999
            def __enter__(self): return self
            def __exit__(self, *a): pass
            def communicate(self, input=None, timeout=None):
                if timeout == 5:
                    return ("", "")
                raise subprocess.TimeoutExpired(self.args, timeout)

        monkeypatch.setattr(subprocess, "Popen", TimeoutPopen)

        with pytest.raises(subprocess.TimeoutExpired):
            run_text(["hang_forever"], timeout=0.1)

        assert len(kill_tree_called) == 1


