class TestL3TreeKill:
    def test_kill_tree_invokes_taskkill_on_windows(self, monkeypatch):
        # Without psutil the Windows path is taskkill. psutil is switched off so a
        # real process that happens to own the fake pid below is never touched.
        monkeypatch.setitem(sys.modules, "psutil", None)
        taskkill_calls = []
        def fake_run(cmd, *a, **k):
            taskkill_calls.append(cmd)
            return SimpleNamespace(returncode=0)

        monkeypatch.setattr(subprocess, "run", fake_run)
        monkeypatch.setattr(os, "name", "nt")

        fake_proc = SimpleNamespace(pid=1234, kill=MagicMock())
        kill_process_tree(fake_proc)

        assert len(taskkill_calls) == 1
        assert taskkill_calls[0] == ["taskkill", "/F", "/T", "/PID", "1234"]
