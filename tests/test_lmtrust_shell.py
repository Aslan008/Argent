class TestL1ShellRouting:
    def test_default_shell_is_powershell(self):
        assert choose_shell("python -m pytest") == "powershell"
        assert choose_shell("git status") == "powershell"

    def test_cmd_chain_operators_route_to_cmd(self):
        assert choose_shell("cd dir && dir") == "cmd"
        assert choose_shell("pytest || echo failed") == "cmd"

    def test_powershell_cmdlets_take_precedence_over_chains(self):
        assert choose_shell("Get-Process | Select-Object -First 5") == "powershell"
        assert choose_shell("Select-String -Path foo.txt -Pattern bar") == "powershell"
        assert choose_shell("$env:PATH") == "powershell"
        assert choose_shell("$x = 10") == "powershell"

    def test_quoted_executable_gets_call_operator_in_powershell(self):
        cmd = '"C:\\Program Files\\Python314\\python.exe" -c "print(1)"'
        argv = build_command_argv(cmd, shell_kind="powershell")
        assert isinstance(argv, list)
        assert argv[0] == "powershell"
        ps_cmd = argv[-1]
        assert ps_cmd.startswith("[Console]::OutputEncoding=[Text.Encoding]::UTF8; & \"C:\\Program Files")

    def test_unquoted_command_does_not_get_double_ampersand(self):
        cmd = "python script.py"
        argv = build_command_argv(cmd, shell_kind="powershell")
        assert "& python" not in argv[-1]
        assert "python script.py" in argv[-1]

    def test_cmd_argv_format_preserves_quotes_with_slash_s(self):
        cmd = 'cd C:\\proj && python -c "print(1)"'
        argv = build_command_argv(cmd, shell_kind="cmd")
        assert argv == 'cmd /s /c "cd C:\\proj && python -c "print(1)""'


