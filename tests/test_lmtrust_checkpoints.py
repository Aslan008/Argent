class TestL2ErrorPaths:
    def test_outside_git_repository_returns_safe_result(self, enable_auto_checkpoint, monkeypatch):
        def fake_git(*args):
            if "rev-parse" in args:
                return SimpleNamespace(returncode=128, stdout="", stderr="fatal: not a git repo")
            return SimpleNamespace(returncode=1, stdout="", stderr="")

        monkeypatch.setattr(cp, "_git", fake_git)
        assert is_git_repo() is False
        res = auto_checkpoint_detailed("some label")
        assert res.sha is None
        assert res.reason == "not a git repository"
        assert res.warn is False

    def test_create_checkpoint_raises_on_commit_failure(self, repo, monkeypatch):
        (repo / "file.py").write_text("v2\n", encoding="utf-8")
        real_git = cp._git

        def fake_git(*args, **kw):
            if args and args[0] == "commit-tree":
                return SimpleNamespace(returncode=1, stdout="", stderr="Please tell me who you are. user.email not set")
            return real_git(*args, **kw)

        monkeypatch.setattr(cp, "_git", fake_git)
        with pytest.raises(CheckpointError, match="git commit-tree failed"):
            create_checkpoint("attempt")
        assert not _git("for-each-ref", "refs/argent").stdout.strip()

    def test_auto_checkpoint_detailed_never_raises(self, monkeypatch):
        def boom(*args):
            raise OSError("git binary missing or killed")
        monkeypatch.setattr(cp, "_git", boom)
        # Must not raise exception
        res = auto_checkpoint_detailed("label")
        assert res.sha is None


