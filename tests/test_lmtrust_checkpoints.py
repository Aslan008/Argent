class TestL4StagedChangesProtection:
    def test_staged_changes_are_snapshotted_without_touching_the_index(self, enable_auto_checkpoint, repo):
        """Staged changes ('M  file.py') no longer skip the checkpoint: the snapshot is
        built in a temporary index, and the user's prepared commit stays exactly as it was."""
        (repo / "file.py").write_text("staged\n", encoding="utf-8")
        _git("add", "file.py")
        before = _git("diff", "--cached").stdout
        res = auto_checkpoint_detailed("test")
        assert res.sha and res.warn is False
        assert _git("diff", "--cached").stdout == before

    def test_untracked_and_unstaged_files_create_checkpoint(self, enable_auto_checkpoint, repo):
        """Unstaged ' M file.py' and untracked '?? new.py' are snapshotted; both stay as they were."""
        (repo / "file.py").write_text("dirty\n", encoding="utf-8")
        (repo / "untracked.py").write_text("new\n", encoding="utf-8")
        res = auto_checkpoint_detailed("turn checkpoint")
        assert res.sha and res.warn is False
        assert set(_git("status", "--porcelain").stdout.splitlines()) == {" M file.py", "?? untracked.py"}
        assert {"file.py", "untracked.py"} <= set(_git("ls-tree", "--name-only", res.sha).stdout.split())


