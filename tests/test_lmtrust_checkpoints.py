    def test_staged_changes_trigger_warning_without_destroying_index(self, enable_auto_checkpoint, monkeypatch):
        """When user has staged changes ('M  file.py'), auto_checkpoint must NOT
        commit `git add -A` over it, but MUST warn the user (warn=True)."""
        def fake_git(*args):
            if "rev-parse" in args and "--is-inside-work-tree" in args:
                return SimpleNamespace(returncode=0, stdout="", stderr="")
            if "status" in args:
                # 'M ' means staged modification (index is dirty by user)
                return SimpleNamespace(returncode=0, stdout="M  staged_file.py\n", stderr="")
            return SimpleNamespace(returncode=0, stdout="", stderr="")

        monkeypatch.setattr(cp, "_git", fake_git)
        res = auto_checkpoint_detailed("test")
        assert res.sha is None
        assert res.warn is True
        assert "git-индексе" in res.reason or "staged" in res.reason

    def test_untracked_and_unstaged_files_create_checkpoint(self, enable_auto_checkpoint, monkeypatch):
        """Unstaged ' M file.py' and untracked '?? new.py' are safely auto-checkpointed."""
