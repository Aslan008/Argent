class TestL3L4L9AutomationMemory:
    def test_key_normalization_and_hashing(self):
        short = "https://example.com/job/123"
        assert mem.normalize_key(short) == short

        # Long item (> 200 chars) gets hashed with sha1 prefix
        long_item = "a" * 250
        norm = mem.normalize_key(long_item)
        assert norm.startswith("sha1:")
        assert len(norm) == 45

    def test_transactional_staging_and_rollback(self, tmp_path, monkeypatch):
        mem_file = tmp_path / "automation_memory.json"
        monkeypatch.setattr(mem, "store_path", lambda: mem_file)

        mem.set_scope("job_monitor")
        items = ["job_1", "job_2"]
        fresh = mem.filter_new(items)
        assert fresh == ["job_1", "job_2"]
        assert mem.pending_count() == 2
        # Not written to disk yet
        assert not mem_file.exists()

        # Rollback drops staged items
        assert mem.rollback() == 2
        assert mem.pending_count() == 0

        # After rollback, same items are still considered new
        fresh_again = mem.filter_new(items)
        assert fresh_again == ["job_1", "job_2"]
        mem.reset_scope()

    def test_transactional_commit_persists_items(self, tmp_path, monkeypatch):
        mem_file = tmp_path / "automation_memory.json"
        monkeypatch.setattr(mem, "store_path", lambda: mem_file)

        mem.set_scope("job_monitor")
        mem.filter_new(["job_A", "job_B"])
        committed_count = mem.commit()
        assert committed_count == 2
        assert mem_file.exists()

        # Second filter_new call sees them as old
        fresh = mem.filter_new(["job_A", "job_C"])
        assert fresh == ["job_C"]
        mem.reset_scope()
