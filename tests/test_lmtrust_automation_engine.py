class TestL1ScheduleParsing:
    def test_empty_and_whitespace_schedules_raise(self):
        with pytest.raises(ScheduleError, match="пустое"):
            parse_schedule("")
        with pytest.raises(ScheduleError, match="пустое"):
            parse_schedule("   ")
        with pytest.raises(ScheduleError, match="пустое"):
            parse_schedule(None)

    def test_interval_parsing_units(self):
        assert parse_schedule("every 15m") == {"kind": "interval", "seconds": 900}
        assert parse_schedule("every 2h") == {"kind": "interval", "seconds": 7200}
        assert parse_schedule("every 1d") == {"kind": "interval", "seconds": 86400}
        assert parse_schedule("EVERY 30 MINS") == {"kind": "interval", "seconds": 1800}

    def test_sub_minute_interval_rejected(self):
        with pytest.raises(ScheduleError, match="интервал слишком мал"):
            parse_schedule("every 0m")

    def test_daily_at_parsing_and_hour_limits(self):
        assert parse_schedule("daily at 09:00") == {"kind": "daily", "hour": 9, "minute": 0}
        assert parse_schedule("daily at 23:59") == {"kind": "daily", "hour": 23, "minute": 59}

        with pytest.raises(ScheduleError, match="неверное время суток"):
            parse_schedule("daily at 25:00")
        with pytest.raises(ScheduleError, match="неверное время суток"):
            parse_schedule("daily at 12:65")


