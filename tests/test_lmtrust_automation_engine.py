class TestL7ScheduleNextRunAndDue:
    def test_interval_never_ran_is_due_immediately(self):
        now = datetime(2026, 8, 28, 12, 0, 0)
        assert next_run_after("every 15m", last_run=None, now=now) == now
        assert is_due("every 15m", last_run=None, now=now) is True

    def test_daily_already_ran_today_schedules_tomorrow(self):
        now = datetime(2026, 8, 28, 10, 0, 0)
        last_run = datetime(2026, 8, 28, 9, 0, 0)
        next_run = next_run_after("daily at 09:00", last_run=last_run, now=now)
        assert next_run == datetime(2026, 8, 29, 9, 0, 0)
        assert is_due("daily at 09:00", last_run=last_run, now=now) is False

    def test_daily_catchup_window(self):
        # 09:00 job, app opened at 09:30 (within 3600s catchup)
        now = datetime(2026, 8, 28, 9, 30, 0)
        next_run = next_run_after("daily at 09:00", last_run=None, now=now)
        assert next_run == datetime(2026, 8, 28, 9, 0, 0)
        assert is_due("daily at 09:00", last_run=None, now=now) is True

        # 09:00 job, app opened at 14:00 (outside 3600s catchup -> wait for tomorrow)
        now_late = datetime(2026, 8, 28, 14, 0, 0)
        next_run_late = next_run_after("daily at 09:00", last_run=None, now=now_late)
        assert next_run_late == datetime(2026, 8, 29, 9, 0, 0)
        assert is_due("daily at 09:00", last_run=None, now=now_late) is False


