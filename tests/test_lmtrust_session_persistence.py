class TestL8L9FindAndFilterSessions:
    def test_find_session_positional_1_based_and_out_of_bounds(self):
        s1 = save_session([{"role": "user", "content": "First session"}], metadata={"label": "Label1"})
        s2 = save_session([{"role": "user", "content": "Second session"}], metadata={"label": "Label2"})

        # Positional 1 is the latest session
        found_1 = find_session("1")
        assert found_1 is not None
        assert found_1["id"] == s2

        # Out of bounds index
        assert find_session("999") is None
        assert find_session("0") is None
        assert find_session("") is None

    def test_find_session_exact_label_priority(self):
        save_session([{"role": "user", "content": "Session alpha"}], metadata={"label": "test"})
        save_session([{"role": "user", "content": "Session beta"}], metadata={"label": "test_extended"})

        found = find_session("test")
        assert found is not None
        assert found["label"] == "test"

    def test_list_sessions_filtered_by_cwd(self, tmp_path):
        dir_a = str(tmp_path / "dir_a")
        dir_b = str(tmp_path / "dir_b")
        save_session([{"role": "user", "content": "Sess A"}], metadata={"cwd": dir_a})
        save_session([{"role": "user", "content": "Sess B"}], metadata={"cwd": dir_b})

        with patch("os.getcwd", return_value=dir_a):
            here_sessions = list_sessions(query="here")
            assert len(here_sessions) == 1
            assert here_sessions[0]["cwd"] == dir_a

    def test_get_last_session(self):
        assert get_last_session() is None
        sid = save_session([{"role": "user", "content": "Latest"}])
        last = get_last_session()
        assert last is not None
        assert last["id"] == sid

    def test_session_rotation_prunes_when_exceeding_max(self, monkeypatch):
        monkeypatch.setattr(session_mod, "MAX_SESSIONS", 3)

        # Create 4 sessions
        sids = []
        for i in range(4):
            sid = f"sess_{i}"
            save_session(
                [{"role": "user", "content": f"Message {i}"}],
                metadata={"model": "test"},
                session_id=sid
            )
            sids.append(sid)

        # After saving 4 sessions with MAX_SESSIONS=3, oldest should be pruned
        active = [s["id"] for s in list_sessions()]
        assert len(active) <= 3

    def test_delete_session_removes_file_and_updates_index(self):
        sid = save_session(
            [{"role": "user", "content": "To be deleted"}],
            metadata={"model": "test"}
        )
        assert sid is not None
        assert load_session(sid) is not None

        # Delete
        ok = delete_session(sid)
        assert ok is True

        # Must be gone from load and listing
        assert load_session(sid) is None
        assert not any(s["id"] == sid for s in list_sessions())
