class TestL5RelativeTimeFormatting:
    def test_format_relative_time_empty_or_broken(self):
        assert format_relative_time("") == "неизвестно"
        assert format_relative_time(None) == "неизвестно"
        assert format_relative_time("invalid_iso_string") == "invalid_iso_stri"

    def test_format_relative_time_just_now(self):
        now = datetime.now()
        iso = (now - timedelta(seconds=25)).isoformat()
        assert format_relative_time(iso) == "только что"

    def test_format_relative_time_minutes_ago(self):
        now = datetime.now()
        iso = (now - timedelta(minutes=15)).isoformat()
        assert format_relative_time(iso) == "15 мин назад"

    def test_format_relative_time_yesterday_and_older(self):
        now = datetime(2026, 8, 28, 15, 0, 0)
        with patch("session.datetime") as mock_dt:
            mock_dt.now.return_value = now
            mock_dt.fromisoformat = datetime.fromisoformat
            mock_dt.side_effect = lambda *a, **kw: datetime(*a, **kw)

            # Yesterday
            yest_iso = datetime(2026, 8, 27, 10, 30, 0).isoformat()
            assert format_relative_time(yest_iso) == "вчера 10:30"

            # Same year earlier
            earlier_iso = datetime(2026, 4, 12, 9, 0, 0).isoformat()
            assert format_relative_time(earlier_iso) == "12.04 09:00"

            # Previous year
            prev_year_iso = datetime(2025, 12, 1, 12, 0, 0).isoformat()
            assert format_relative_time(prev_year_iso) == "01.12.2025"


