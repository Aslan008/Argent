class TestL6ShortPathFormatting:
    def test_format_short_path_empty(self):
        assert format_short_path("") == ""
        assert format_short_path(None) == ""

    def test_format_short_path_relative_to_home(self, tmp_path, monkeypatch):
        fake_home = tmp_path / "home_user"
        fake_home.mkdir()
        monkeypatch.setattr(Path, "home", classmethod(lambda cls: fake_home))

        sub_path = fake_home / "projects" / "argent"
        assert format_short_path(str(sub_path)) == "~/projects/argent"

    def test_format_short_path_outside_home(self, tmp_path, monkeypatch):
        fake_home = tmp_path / "home_user"
        fake_home.mkdir()
        monkeypatch.setattr(Path, "home", classmethod(lambda cls: fake_home))

        outside = tmp_path / "other_dir" / "file.txt"
        res = format_short_path(str(outside))
        assert not res.startswith("~/")
        assert "other_dir/file.txt" in res or "other_dir\\file.txt" in res


