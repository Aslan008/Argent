class TestL1SanitizationAndExtraction:
    def test_sanitize_for_filename_replaces_illegal_windows_chars(self):
        raw = 'model:claude-3.5/sonnet\\v1*?"<>| test'
        sanitized = _sanitize_for_filename(raw)
        for illegal in '.\\/:*?"<>| ':
            assert illegal not in sanitized
        assert sanitized != ""

    def test_first_user_message_skips_injected_system_prompts(self):
        messages = [
            {"role": "system", "content": "You are a helpful assistant"},
            {"role": "user", "content": "you are an automated runner"},  # injected
            {"role": "user", "content": "your tool call was cut off"},   # injected
            {"role": "user", "content": "Real human user question!"},    # target
            {"role": "assistant", "content": "Here is the answer"},
        ]
        assert _first_user_message(messages) == "Real human user question!"

    def test_first_user_message_returns_none_when_no_real_user(self):
        messages = [
            {"role": "system", "content": "System prompt"},
            {"role": "assistant", "content": "Intro"},
        ]
        assert _first_user_message(messages) is None

    def test_make_serializable_handles_non_json_types(self):
        messages = [
            {"role": "user", "content": "Hello", "custom_obj": object(), "number": 42}
        ]
        clean = _make_serializable(messages)
        assert clean[0]["content"] == "Hello"
        assert clean[0]["number"] == 42
        assert isinstance(clean[0]["custom_obj"], str)


