    def test_save_empty_session_returns_none(self):
        res = save_session([], metadata={"model": "gpt-4o"})
        assert res is None

    def test_save_and_load_roundtrip_preserves_messages_and_cwd(self, tmp_path):
        cwd_dir = str(tmp_path / "project_alpha")
        messages = [
            {"role": "user", "content": "Build the backend API"},
            {"role": "assistant", "content": "Understood."},
        ]
        sid = save_session(messages, metadata={"model": "claude-3-7-sonnet", "cwd": cwd_dir})
