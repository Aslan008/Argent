class TestL1L4SalvageAndVerification:
    def test_decode_partial_removes_dangling_backslash_and_unescapes(self):
        # Single dangling backslash at EOF is stripped
        raw_dangling = 'line 1\\nline 2\\tindent\\"quote\\'
        assert _decode_partial(raw_dangling) == 'line 1\nline 2\tindent"quote'

        # Escaped double backslash at EOF is preserved as single backslash
        raw_escaped = 'path\\\\folder\\\\'
        assert _decode_partial(raw_escaped) == 'path\\folder\\'

    def test_extract_partial_write_from_truncated_json_string(self):
        truncated_json = '{"path": "src/app.py", "content": "def main():\\n    print(\\"hello\\")\\n    x = 10'
        res = extract_partial_write(truncated_json)
        assert res is not None
        file_path, content = res
        assert file_path == "src/app.py"
        assert content == 'def main():\n    print("hello")\n    x = 10'

    def test_trim_to_last_line(self):
        multiline = "line 1\nline 2\npartial_tok"
        assert trim_to_last_line(multiline) == "line 1\nline 2\n"

        single = "only one line without newline"
        assert trim_to_last_line(single) == single

    def test_verify_salvaged_file_python_and_json(self, tmp_path):
        py_good = tmp_path / "good.py"
        py_good.write_text("def foo():\n    return 42\n", encoding="utf-8")
        assert verify_salvaged_file(str(py_good)) == (True, "")

        py_bad = tmp_path / "bad.py"
        py_bad.write_text("def foo():\n    incomplete syntax (", encoding="utf-8")
        ok, detail = verify_salvaged_file(str(py_bad))
        assert ok is False
        assert "Python syntax error" in detail

        json_good = tmp_path / "good.json"
        json_good.write_text('{"status": "ok"}', encoding="utf-8")
        assert verify_salvaged_file(str(json_good)) == (True, "")

        json_bad = tmp_path / "bad.json"
        json_bad.write_text('{"status": "truncated', encoding="utf-8")
        ok_j, detail_j = verify_salvaged_file(str(json_bad))
        assert ok_j is False
        assert "invalid JSON" in detail_j
