class TestL4L7RoomGraphValidation:
    def test_valid_room_passes_validation(self):
        room = Room(
            room="test_room",
            entry="node_1",
            budget=Budget(max_iterations=10, max_tokens=2000),
            nodes=[
                Node(id="node_1", type="tool", tool="read_file"),
                Node(id="node_2", type="human_pause"),
            ],
            edges=[
                Edge(from_="node_1", to="node_2"),
                Edge(from_="node_2", to="EXIT:success"),
            ],
        )
        errors = validate_room(room, available_tools={"read_file"})
        assert errors == []

    def test_unreachable_dead_end_nodes_detected(self):
        """Graph fixpoint must detect nodes that cannot reach any EXIT."""
        room = Room(
            room="loop_room",
            entry="node_1",
            budget=Budget(max_iterations=10, max_tokens=2000),
            nodes=[
                Node(id="node_1", type="tool", tool="read_file"),
                Node(id="stuck_loop_a", type="tool", tool="read_file"),
                Node(id="stuck_loop_b", type="tool", tool="read_file"),
            ],
            edges=[
                Edge(from_="node_1", to="EXIT:done"),
                Edge(from_="stuck_loop_a", to="stuck_loop_b"),
                Edge(from_="stuck_loop_b", to="stuck_loop_a"),  # Infinite loop without EXIT
            ],
        )
        errors = validate_room(room, available_tools={"read_file"})
        assert any("cannot reach any EXIT" in e and "stuck_loop_a" in e for e in errors)

    def test_unknown_tool_and_spawn_permission_gates(self):
        room = Room(
            room="spawn_test",
            entry="spawner",
            budget=Budget(max_iterations=10, max_tokens=2000),
            nodes=[
                Node(id="spawner", type="spawn_room"),
                Node(id="bad_tool_node", type="tool", tool="nonexistent_tool_xyz"),
            ],
            edges=[
                Edge(from_="spawner", to="bad_tool_node"),
                Edge(from_="bad_tool_node", to="EXIT:done"),
            ],
        )
        # When allow_spawn is False (non-triage room)
        errors = validate_room(room, available_tools={"read_file"}, allow_spawn=False)
        assert any("spawn_room is only allowed in the triage room" in e for e in errors)
        assert any("tool 'nonexistent_tool_xyz' does not exist" in e for e in errors)
