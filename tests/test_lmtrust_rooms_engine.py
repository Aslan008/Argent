class TestL3L9JournalPersistence:
    def test_journal_appends_and_reads_records(self, tmp_path):
        j_file = tmp_path / "room.journal.jsonl"
        j = Journal(j_file)

        j.append({"type": "intent", "node": "step_1", "state": {"x": 1}})
        j.append({"type": "commit", "node": "step_1", "next": "step_2"})

        recs = j.records()
        assert len(recs) == 2
        assert j.last()["type"] == "commit"

    def test_journal_tolerates_torn_final_line_from_crash(self, tmp_path):
        j_file = tmp_path / "room.journal.jsonl"
        j = Journal(j_file)

        j.append({"type": "intent", "node": "step_1"})
        # Simulate crash mid-write appending a broken line
        with open(j_file, "a", encoding="utf-8") as f:
            f.write('{"type": "commit", "node": "step_1", "broken_json...')

        recs = j.records()
        # Must gracefully parse the first valid record and ignore the truncated torn line
        assert len(recs) == 1
        assert recs[0]["node"] == "step_1"


