class TestL2L4QuarantineAndPersistence:
    def test_corrupted_json_is_quarantined_and_starts_fresh(self, tmp_path, monkeypatch):
        mem_file = tmp_path / ".argent" / "memory.json"
        mem_file.parent.mkdir(parents=True, exist_ok=True)
        mem_file.write_text("{broken json syntax: [1, 2,", encoding="utf-8")

        monkeypatch.setattr(memory_manager, "resolve_memory_file", lambda: mem_file)
        mgr = MemoryManager()

        # Data starts fresh
        assert mgr.data["objective"] == ""
        # The broken file must have been renamed to .broken-<timestamp>
        broken_backups = list(mem_file.parent.glob("memory.json.broken-*"))
        assert len(broken_backups) == 1
        assert "{broken json syntax" in broken_backups[0].read_text(encoding="utf-8")

    def test_corrupted_list_types_coerced_gracefully(self, tmp_path, monkeypatch):
        mem_file = tmp_path / ".argent" / "memory.json"
        mem_file.parent.mkdir(parents=True, exist_ok=True)
        # corrupted: completed is a string instead of a list
        corrupted_payload = {
            "objective": "Fix bug",
            "completed": "Not a list!",
            "key_facts": [123, True, "Valid fact"],
        }
        mem_file.write_text(json.dumps(corrupted_payload), encoding="utf-8")

        monkeypatch.setattr(memory_manager, "resolve_memory_file", lambda: mem_file)
        mgr = MemoryManager()
        assert mgr.data["objective"] == "Fix bug"
        assert isinstance(mgr.data["completed"], list)
        assert mgr.data["completed"] == ["Not a list!"]
        assert mgr.data["key_facts"] == ["123", "True", "Valid fact"]


