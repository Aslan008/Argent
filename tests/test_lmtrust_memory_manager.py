class TestL3L9ContextNoteAndLifecycle:
    def test_build_context_note_formats_cleanly_with_exact_subsets(self, temp_memory_mgr):
        mgr, _ = temp_memory_mgr
        mgr.set_objective("Refactor core engine")
        mgr.set_current_task("Writing LMTrust tests")
        for i in range(12):
            mgr.add_completed(f"Done {i}")
        for i in range(15):
            mgr.add_file_modified(f"src/file_{i}.py")
        for i in range(8):
            mgr.add_fact(f"Fact {i}")
        for i in range(5):
            mgr.add_error(f"Error {i}")

        note = mgr.build_context_note()
        assert "OBJECTIVE: Refactor core engine" in note
        assert "CURRENT TASK: Writing LMTrust tests" in note
        assert "COMPLETED ACTIONS:" in note
        # Completed actions shows last 8
