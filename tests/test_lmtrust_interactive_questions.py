class TestL2L4PayloadAndFallbacks:
    def test_malformed_json_string_returns_error(self):
        res = ask_user_questions("{broken_json: true")
        assert "Error: 'questions' must be a JSON array of objects" in res

    def test_single_dict_payload_unwrapped_automatically(self, monkeypatch):
        monkeypatch.setattr("prompt_toolkit.prompt", lambda *a, **k: "My answer")
        res = ask_user_questions({"type": "text", "question": "Single question?"})
        assert "User responses:" in res
        assert "- Single question?: My answer" in res

    def test_empty_or_non_list_questions_return_error(self):
        assert "Error: 'questions' must be a non-empty" in ask_user_questions([])
        assert "Error: 'questions' must be a non-empty" in ask_user_questions(12345)

    def test_choice_question_with_zero_options_falls_back_to_free_text(self, monkeypatch):
        """When single_choice has no valid options, it must ask as free text rather than crashing."""
        monkeypatch.setattr("prompt_toolkit.prompt", lambda *a, **k: "Fell back to text")
        payload = [
            {"type": "single_choice", "question": "Pick option?", "options": []}
        ]
        res = ask_user_questions(payload)
        assert "User responses:" in res
        assert "- Pick option?: Fell back to text" in res


