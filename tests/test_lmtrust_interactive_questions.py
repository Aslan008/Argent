class TestL3L7InteractiveFlows:
    def test_keyboard_interrupt_recorded_as_skipped(self, monkeypatch):
        def raise_sigint(*a, **k):
            raise KeyboardInterrupt()

        monkeypatch.setattr("prompt_toolkit.prompt", raise_sigint)
        payload = [{"type": "text", "question": "Will be cancelled"}]
        res = ask_user_questions(payload)
        assert "User responses:" in res
        assert "- Will be cancelled: Skipped" in res

    def test_custom_write_in_option_in_single_choice(self, monkeypatch):
        CUSTOM = "✏ Свой вариант..."
        monkeypatch.setattr("questionary.select", lambda *a, **k: SimpleNamespace(ask=lambda: CUSTOM))
        monkeypatch.setattr("prompt_toolkit.prompt", lambda *a, **k: "Custom typed answer")

        payload = [{
            "type": "single_choice",
            "question": "Which architecture?",
            "options": ["Monolith", "Microservices"]
        }]
        res = ask_user_questions(payload)
        assert "User responses:" in res
        assert "- Which architecture?: Custom typed answer" in res

    def test_fit_options_formats_long_strings_cleanly(self, monkeypatch):
        import os
        monkeypatch.setattr("shutil.get_terminal_size", lambda *a, **k: os.terminal_size((80, 30)))
        long_opts = ["A" * 120, "B" * 120]
        fitted, listing = _fit_options(long_opts)
        assert len(fitted) == 2
        assert fitted[0][0].endswith("…")
        assert fitted[0][1] == "A" * 120
        assert listing != ""
