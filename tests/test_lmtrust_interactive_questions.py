# LAYER L1: Option Text Normalization & Deduplication
# ============================================================================

class TestL1OptionNormalization:
    def test_option_text_from_various_types(self):
        assert _option_text("Simple string") == "Simple string"
        assert _option_text({"label": "From label"}) == "From label"
        assert _option_text({"title": "From title"}) == "From title"
        assert _option_text({"text": "From text"}) == "From text"
        assert _option_text({"value": "From value"}) == "From value"
        assert _option_text(["Single item", False]) == "Single item"
        assert _option_text(123) == "123"

        # Invalid / rejected
        assert _option_text(["Two", "strings"]) is None
        assert _option_text("") is None
        assert _option_text("   ") is None
        assert _option_text(None) is None
        assert _option_text({}) is None

    def test_normalize_options_deduplicates_and_collects_rejected(self):
        raw = [
            "Option A",
            {"label": "Option B"},
            "Option A",  # duplicate
            "",          # rejected
            None,        # rejected
            {"text": "Option C"},
        ]
        texts, rejected = _normalize_options(raw)
        assert texts == ["Option A", "Option B", "Option C"]
        assert len(rejected) == 2


