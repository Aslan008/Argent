class TestL2ErrorPathsAndCircuitBreaker:
    def setup_method(self):
        trimmer._TOKEN_CACHE.clear()
        trimmer._API_TOKENIZE_BROKEN.clear()

    def test_circuit_breaker_trips_on_network_error(self, monkeypatch):
        def mock_post(*args, **kwargs):
            raise ConnectionError("Ollama is unreachable")
        monkeypatch.setattr("requests.post", mock_post)

        res = _query_tokenize_api("test", "llama3", "ollama")
        assert res is None
        assert "ollama" in trimmer._API_TOKENIZE_BROKEN

        # Next call to estimate_tokens should NOT attempt _query_tokenize_api
        query_mock = MagicMock()
        monkeypatch.setattr(trimmer, "_query_tokenize_api", query_mock)
        estimate_tokens("another text", "llama3", "ollama")
        query_mock.assert_not_called()

    def test_deterministic_facts_extraction_handles_malformed_tool_args(self):
        messages = [
            {"role": "assistant", "tool_calls": [
                {"function": {"name": "write_file", "arguments": "{broken_json"}},
                {"function": {"name": "run_command", "arguments": {"command": "pytest tests/"}}}
            ]},
            {"role": "tool", "content": "Traceback (most recent call last):\nValueError: Boom"}
        ]
        facts = _extract_deterministic_facts(messages)
        assert "**Команды:** pytest tests/" in facts
        assert "**Ошибки:**" in facts
        assert "ValueError: Boom" in facts

    def test_create_distillate_falls_back_when_llm_fails(self, monkeypatch):
        monkeypatch.setattr(trimmer, "_summarize_with_llm", lambda *a, **k: None)
        msgs = [
            {"role": "system", "content": "sys"},
            {"role": "user", "content": "Сделай оптимизацию контекста"},
            {"role": "assistant", "tool_calls": [
                {"function": {"name": "write_file", "arguments": json.dumps({"file_path": "src/agent/trimmer.py"})}}
            ]},
            {"role": "tool", "content": "File written successfully"}
        ]
        distillate = trimmer._create_distillate(
            msgs_to_compress=msgs[1:],
            all_messages=msgs,
            active_window_start=3,
            existing_distillate=None,
            model_name="test-model"
        )
        assert "**ACTIVE GOAL:** Сделай оптимизацию контекста" in distillate
        assert "src/agent/trimmer.py" in distillate


