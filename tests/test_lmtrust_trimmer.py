class TestL4FileRehydrationAndBoundaries:
    def test_rehydrate_files_truncates_huge_files(self, tmp_path):
        big_file = tmp_path / "big_file.py"
        content = ("# HEAD\n" + "x" * 10000 + "\n# TAIL")
        big_file.write_text(content, encoding="utf-8")

        messages = [
            {"role": "assistant", "tool_calls": [
                {"function": {"name": "write_file", "arguments": json.dumps({"file_path": str(big_file)})}}
            ]}
        ]
        rehydrated = _rehydrate_files(messages, max_files=1, max_chars_per_file=500)
        assert "big_file.py" in rehydrated
        assert "символов пропущено" in rehydrated
        assert "# HEAD" in rehydrated
        assert "# TAIL" in rehydrated

    def test_rehydrate_files_ignores_missing_files(self):
        messages = [
            {"role": "assistant", "tool_calls": [
                {"function": {"name": "write_file", "arguments": json.dumps({"file_path": "non_existent_file_12345.py"})}}
            ]}
        ]
        res = _rehydrate_files(messages)
        assert res == ""

    def test_write_compact_boundary_appends_jsonl(self, tmp_path, monkeypatch):
        import project_paths
        monkeypatch.setattr(project_paths, "project_root_or_cwd", lambda: tmp_path)

        before = [{"role": "user"}, {"role": "assistant"}, {"role": "user"}]
        after = [{"role": "user"}]
        _write_compact_boundary(before, after, compression_id=1)

        log_file = tmp_path / ".argent" / "compact_log.jsonl"
        assert log_file.exists()
        lines = log_file.read_text(encoding="utf-8").strip().splitlines()
        assert len(lines) == 1
        entry = json.loads(lines[0])
        assert entry["compression_id"] == 1
        assert entry["messages_dropped"] == 2


