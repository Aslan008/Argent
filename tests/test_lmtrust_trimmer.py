class TestL9AgingAndCompaction:
    def test_age_tool_results_replaces_old_dumps(self):
        # 8 turns ago tool call
        messages = [
            {"role": "system", "content": "System"},
            {"role": "assistant", "tool_calls": [{"id": "call_1", "function": {"name": "read_file", "arguments": json.dumps({"file_path": "main.py"})}}]},
            {"role": "tool", "tool_call_id": "call_1", "content": "print('hello')\n" * 30},
        ]
        # Add 7 user turns
        for i in range(7):
            messages.extend([
                {"role": "user", "content": f"Substantive task step {i}"},
                {"role": "assistant", "content": "Done"},
            ])

        aged = age_tool_results(messages, age_threshold=6)
        tool_msg = aged[2]
        assert tool_msg["content"].startswith("[aged: read_file(main.py)")

    def test_compact_tool_history_preserves_recent(self):
        messages = [
            {"role": "tool", "content": "x" * 500},
            {"role": "tool", "content": "y" * 500},
            {"role": "tool", "content": "z" * 500},
        ]
        # keep_recent = 2, so only 1st is stubbed
        compacted = compact_tool_history(messages, keep_recent=2, stub_over=200)
        assert "tool output trimmed" in compacted[0]["content"]
        assert len(compacted[1]["content"]) == 500
        assert len(compacted[2]["content"]) == 500

    def test_compact_image_history_keeps_recent_payloads(self):
        messages = [
            {"role": "user", "content": "shot 1", "images": ["img1"]},
            {"role": "user", "content": "shot 2", "images": ["img2"]},
            {"role": "user", "content": "shot 3", "images": ["img3"]},
        ]
        compacted = compact_image_history(messages, keep_recent=2)
        assert "images" not in compacted[0]
        assert "изобр. показано ранее" in compacted[0]["content"]
        assert "images" in compacted[1]
        assert "images" in compacted[2]

    def test_hard_reset_with_memory_preserves_root_and_last_user(self):
        messages = [
            {"role": "system", "content": "System Prompt"},
            {"role": "user", "content": "Первоначальная цель: создать игру"},
            {"role": "assistant", "content": "Создаю скелет игры..."},
            {"role": "user", "content": "Добавь управление клавишами WASD"},
        ]
        reset_msgs = hard_reset_with_memory(messages, model_name="test-model")
        assert len(reset_msgs) == 3
        assert reset_msgs[0]["role"] == "system"
        assert "=== CONTEXT DISTILLATE (emergency reset) ===" in reset_msgs[1]["content"]
        assert reset_msgs[2]["content"] == "Добавь управление клавишами WASD"
