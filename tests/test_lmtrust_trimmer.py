class TestL1TokenEstimation:
    def setup_method(self):
        trimmer._TOKEN_CACHE.clear()
        trimmer._API_TOKENIZE_BROKEN.clear()

    def test_estimate_empty_and_null_text(self):
        assert estimate_tokens("", "gpt-4", "openai") == 0
        assert estimate_tokens(None, "gpt-4", "openai") == 0

    def test_heuristic_cyrillic_vs_ascii(self):
        ascii_text = "a" * 100
        cyrillic_text = "а" * 100
        # Cyrillic should yield significantly more tokens per character
        ascii_est = _heuristic_tokens(ascii_text)
        cyrillic_est = _heuristic_tokens(cyrillic_text)
        assert ascii_est == 25
        assert cyrillic_est > ascii_est
        assert cyrillic_est == int(100 / 1.8)

    def test_token_cache_eviction_at_max(self, monkeypatch):
        monkeypatch.setattr(trimmer, "_TOKEN_CACHE_MAX", 3)
        trimmer._TOKEN_CACHE.clear()
        estimate_tokens("text 1", "model", "provider")
        estimate_tokens("text 2", "model", "provider")
        estimate_tokens("text 3", "model", "provider")
        assert len(trimmer._TOKEN_CACHE) == 3
        # 4th item clears the cache and adds new key
        estimate_tokens("text 4", "model", "provider")
        assert len(trimmer._TOKEN_CACHE) == 1

    def test_estimate_message_tokens_with_images(self):
        # Plain message
        msg_text = {"role": "user", "content": "hello world"}
        tokens_text = estimate_message_tokens(msg_text, "model", "ollama")
        assert tokens_text > 0

        # Message with 2 images
        msg_images = {"role": "user", "content": "look", "images": ["img_base64_1", "img_base64_2"]}
        tokens_img = estimate_message_tokens(msg_images, "model", "ollama")
        assert tokens_img >= 2 * IMAGE_TOKEN_COST

    def test_estimate_message_tokens_non_dict_fallback(self):
        assert estimate_message_tokens("plain string", "model", "ollama") > 0


class TestL1SubstantiveGoalDetection:
    def test_trivial_words_filtered(self):
        trivials = ["ок", "OK", "  давай  ", "продолжай", "делай плиз", "ага, понял", "yes please"]
        for t in trivials:
            assert not _is_substantive(t), f"Failed for: {t}"

    def test_short_and_prefixed_filtered(self):
        assert not _is_substantive("hi")
        assert not _is_substantive("        ")
        assert not _is_substantive("/commit")
        assert not _is_substantive("[Heartbeat пробуждение]")
        assert not _is_substantive("[Режим Автоматизма] Продолжай работу")

    def test_substantive_tasks_recognized(self):
        substantives = [
            "Напиши юнит тесты для модуля trimmer",
            "Fix memory leak in websocket connection",
            "Рефакторинг парсера markdown",
        ]
        for s in substantives:
            assert _is_substantive(s), f"Failed for: {s}"

    def test_find_active_goal_truncation(self):
        long_task = "Задача: " + ("X" * 600)
        messages = [
            {"role": "system", "content": "System"},
            {"role": "user", "content": long_task},
            {"role": "assistant", "content": "Working"},
            {"role": "user", "content": "ok"},
        ]
        goal = _find_active_goal(messages, active_window_start=3)
        assert goal is not None
        assert goal.endswith("…")
        assert len(goal) == 501  # 500 chars + '…'


