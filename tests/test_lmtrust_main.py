class TestL4SessionRestoration:
    def test_restore_session_missing_data_returns_false(self, monkeypatch):
        monkeypatch.setattr("src.startup.load_session", lambda sid: None)
        fake_agent = SimpleNamespace(messages=[], session_id=None)
        res = restore_session(fake_agent, {"id": "nonexistent_session"})
        assert res is False

    def test_restore_session_loads_messages_and_warns_model_mismatch(self, monkeypatch):
        saved_payload = {
            "id": "sess_123",
            "saved_at": "2026-08-28 20:00:00",
            "model": "claude-3-5-sonnet",
            "cwd": str(Path.cwd()),
            "messages": [{"role": "user", "content": "hello"}],
        }
        monkeypatch.setattr("src.startup.load_session", lambda sid: saved_payload)
        printed = []
        monkeypatch.setattr("ui.print_system", lambda text: printed.append(text))

        fake_agent = SimpleNamespace(messages=[], session_id=None, model_name="gpt-4o")
        ok = restore_session(fake_agent, {"id": "sess_123"})
        assert ok is True
        assert fake_agent.session_id == "sess_123"
        assert len(fake_agent.messages) == 1
        assert any("claude-3-5-sonnet" in p and "gpt-4o" in p for p in printed)

    def test_restore_session_missing_directory_handled(self, monkeypatch):
        saved_payload = {
            "id": "sess_456",
            "cwd": "C:/nonexistent_folder_abc_xyz_123",
            "messages": [{"role": "user", "content": "hello"}],
        }
        monkeypatch.setattr("src.startup.load_session", lambda sid: saved_payload)
        printed = []
        monkeypatch.setattr("ui.print_system", lambda text: printed.append(text))

        fake_agent = SimpleNamespace(messages=[], session_id=None, model_name="")
        ok = restore_session(fake_agent, {"id": "sess_456"})
        assert ok is True
        assert any("Директории сессии больше нет" in p for p in printed)

    def test_restore_session_user_declines_cd(self, monkeypatch, tmp_path):
        saved_payload = {
            "id": "sess_789",
            "cwd": str(tmp_path),
            "messages": [{"role": "user", "content": "hello"}],
        }
        monkeypatch.setattr("src.startup.load_session", lambda sid: saved_payload)
        printed = []
        monkeypatch.setattr("ui.print_system", lambda text: printed.append(text))
        monkeypatch.setattr("questionary.confirm", lambda *a, **k: SimpleNamespace(ask=lambda: False))

        fake_agent = SimpleNamespace(messages=[], session_id=None, model_name="")
        ok = restore_session(fake_agent, {"id": "sess_789"})
