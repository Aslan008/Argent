class TestL1L2HealingFailureDetection:
    def test_non_healing_tools_never_trigger_healing(self):
        assert detect_tool_failure("read_file", "Error: File not found") is False
        assert detect_tool_failure("list_directory", "Error reading dir") is False

    def test_zero_exit_code_and_zero_failures_not_detected_as_failure(self):
        output = "Exit code: 0\n====== 15 passed, 0 failed in 0.5s ======"
        assert detect_tool_failure("run_command", output) is False

    def test_nonzero_exit_code_triggers_healing(self):
        output = "Exit code: 1\n====== 1 failed, 14 passed in 0.5s ======"
        assert detect_tool_failure("run_command", output) is True

