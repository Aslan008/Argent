# LAYER L3 / L4 / L5: Command Diagnostics (PowerShell, Locales, Compilers, MSBuild)
# ============================================================================

class TestL3L4L5CommandDiagnostics:
    def test_zero_exit_code_returns_none(self):
        assert diagnose_command_error("pytest", "passed", exit_code=0) is None

    def test_powershell_cmdlet_in_cmd_diagnosed(self):
        cmd = "Select-Object -First 5"
        output = "'Select-Object' is not recognized as an internal or external command"
        diag = diagnose_command_error(cmd, output, exit_code=1)
        assert "Select-Object" in diag
        assert "PowerShell cmdlet but the command was run in cmd.exe" in diag

    def test_russian_locale_unrecognized_command(self):
        cmd = "npx some-missing-tool"
        output = "'npx' не является внутренней или внешней командой"
        diag = diagnose_command_error(cmd, output, exit_code=1)
        assert "Check it is installed and on PATH" in diag

        output_alt = "не является внутренней либо внешней командой"
        diag_alt = diagnose_command_error(cmd, output_alt, exit_code=1)
        assert "Check it is installed and on PATH" in diag_alt

    def test_access_denied_suggests_run_admin_command(self):
        diag = diagnose_command_error("net stop wuauserv", "Access is denied.", exit_code=5)
        assert "run_admin_command" in diag

        diag_ru = diagnose_command_error("cmd", "отказано в доступе", exit_code=5)
        assert "run_admin_command" in diag_ru

    def test_csharp_compiler_error_codes_extracted(self):
        output = "Program.cs(12,5): error CS0103: The name 'foo' does not exist in the current context"
        diag = diagnose_command_error("dotnet build", output, exit_code=1)
        assert "CS0103" in diag
        assert "The C# compiler reported errors" in diag

    def test_msbuild_error_diagnosed(self):
        output = "MSB4019: The imported project Microsoft.CSharp.targets was not found"
        diag = diagnose_command_error("msbuild app.csproj", output, exit_code=1)
        assert "MSBuild reported an error" in diag

    def test_python_traceback_guidance(self):
        output = "Traceback (most recent call last):\n  File 'test.py', line 5\nZeroDivisionError: division by zero"
        diag = diagnose_command_error("python test.py", output, exit_code=1)
        assert "Python raised an exception" in diag
        assert "Read the LAST line of the traceback" in diag

    def test_npm_and_enoent_diagnosed(self):
        output = "npm ERR! code ENOENT\nnpm ERR! syscall open"
        diag = diagnose_command_error("npm run dev", output, exit_code=1)
        assert "npm/node error" in diag
        assert "ENOENT" in diag

    def test_path_not_found_variations(self):
        diag1 = diagnose_command_error("cat /missing/file", "no such file or directory", exit_code=1)
        assert "A file or directory in the command was not found" in diag1

        diag2 = diagnose_command_error("dir missing", "не удается найти указанный файл", exit_code=1)
        assert "A file or directory in the command was not found" in diag2
