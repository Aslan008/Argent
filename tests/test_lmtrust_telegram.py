class TestL7TelegramAuthorization:
    def test_unauthorized_user_message_rejected_silently_when_paired(self, monkeypatch, caplog):
        bridge = TelegramBridge()
        monkeypatch.setattr("src.telegram.bot.get_telegram_chat_id", lambda: "123456")

        sent_messages = []
        fake_client = SimpleNamespace(
            send_message=lambda chat_id, text, **kw: sent_messages.append((chat_id, text)),
            answer_callback_query=lambda *a, **k: True,
        )
        bridge.client = fake_client

        # Update from unauthorized user 999999 when paired with 123456
        unauth_update = {
            "message": {
                "chat": {"id": 999999},
                "from": {"first_name": "Eve", "username": "eve"},
                "text": "run malicious command",
            }
        }
        with caplog.at_level("WARNING"):
            bridge._handle_update(unauth_update)

        # Silent drop: no response sent to intruder
        assert len(sent_messages) == 0
        assert "Rejected unauthorized message from chat_id 999999" in caplog.text

