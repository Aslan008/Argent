class TestL1TelegramHtmlFormatting:
    def test_empty_and_null_text(self):
        assert format_html("") == ""
        assert format_html(None) == ""

    def test_html_special_chars_escaped_outside_code(self):
        raw = "Check <div> & <script>alert(1)</script>"
        res = format_html(raw)
        assert "&lt;div&gt;" in res
        assert "&amp;" in res
        assert "<script>" not in res

    def test_fenced_code_blocks_escaped_and_tagged(self):
        raw = "Here is code:\n```python\nx = 1 < 2 & True\nprint('ok')\n```\nDone."
        res = format_html(raw)
        assert '<pre><code class="language-python">' in res
        assert "&lt; 2 &amp; True" in res
        assert "</code></pre>" in res
        assert "Done." in res

    def test_inline_code_escaped(self):
        raw = "Use `x < 5 && y > 2` for check"
        res = format_html(raw)
        assert "<code>x &lt; 5 &amp;&amp; y &gt; 2</code>" in res

    def test_markdown_headers_converted_to_bold(self):
        raw = "### Important Note\nContent here"
        res = format_html(raw)
        assert "<b>Important Note</b>" in res

    def test_bold_and_italic_conversions(self):
        raw = "This is **bold** and *italic* text"
        res = format_html(raw)
        assert "<b>bold</b>" in res
        assert "<i>italic</i>" in res

    def test_strikethrough_and_bullet_lists(self):
        raw = "- Item 1\n* Item 2\n~~deleted~~"
        res = format_html(raw)
        assert "• Item 1" in res
        assert "• Item 2" in res
        assert "<s>deleted</s>" in res

    def test_links_converted_to_a_tags(self):
        raw = "Visit [Argent Docs](https://github.com/argent)"
        res = format_html(raw)
        assert '<a href="https://github.com/argent">Argent Docs</a>' in res


