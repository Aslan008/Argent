class TestL2L4ChunkingAndFallbacks:
    def test_chunk_text_splits_at_newline_or_space(self):
        # 100 lines of 50 chars each = 5000 chars
        lines = [f"Line {i} " + ("x" * 40) for i in range(100)]
        big_text = "\n".join(lines)

        chunks = TelegramClient._chunk_text(big_text, limit=1000)
        assert len(chunks) > 1
        for c in chunks:
            assert len(c) <= 1000

    def test_format_markdown_for_telegram_splits_paragraphs(self):
        p1 = "Paragraph 1: " + ("a" * 2000)
        p2 = "Paragraph 2: " + ("b" * 2000)
        combined = f"{p1}\n\n{p2}"

        chunks = format_markdown_for_telegram(combined, limit=2500)
        assert len(chunks) == 2
        assert "Paragraph 1" in chunks[0]
        assert "Paragraph 2" in chunks[1]

    def test_send_message_retries_as_plain_text_if_html_fails(self, monkeypatch):
        client = TelegramClient("fake_token")
        calls = []

        def fake_call(method, payload, **kwargs):
            calls.append(dict(payload))
            # First call with parse_mode=HTML returns None (simulating parse error)
            if payload.get("parse_mode") == "HTML":
                return None
            # Retry without parse_mode succeeds
            return {"ok": True, "result": {"message_id": 101}}

        monkeypatch.setattr(client, "_call", fake_call)
        res = client.send_message(12345, "Broken <b>HTML <unclosed>", parse_mode="HTML")
        assert res is not None
        assert len(calls) == 2
        assert calls[0].get("parse_mode") == "HTML"
        assert "parse_mode" not in calls[1]


