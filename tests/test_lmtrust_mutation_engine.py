# LAYER L1 / L4: AST Skip Ranges & Offset Calculations
# ============================================================================

class TestL1L4ASTSkipRangesAndOffsets:
    def test_pos_to_offset_multiline_calculation(self):
        source = "line 1\nline 2\nline 3\n"
        # Line 1, Col 0 -> 0
        assert _pos_to_offset(source, (1, 0)) == 0
        # Line 2, Col 3 -> offset of 'e' in 'line 2' (7 + 3 = 10)
        assert _pos_to_offset(source, (2, 3)) == 10
        # Line 3, Col 0 -> 14
        assert _pos_to_offset(source, (3, 0)) == 14

    def test_compute_skip_ranges_skips_comments_strings_and_return_annotations(self):
        source = (
            '"""Module docstring."""\n'
            '# Comment line\n'
            'def calculate(x: int) -> int:\n'
            '    greeting = "Hello + world"\n'
            '    return x + 1\n'
        )
        skip_ranges = compute_skip_ranges(source)

        # 1. Docstring must be in skip ranges
        doc_pos = source.find("Module docstring")
        assert _is_in_skip(doc_pos, skip_ranges) is True

        # 2. Comment must be in skip ranges
        comment_pos = source.find("Comment line")
        assert _is_in_skip(comment_pos, skip_ranges) is True

        # 3. String literal "Hello + world" must be in skip ranges
        str_pos = source.find("Hello + world")
        assert _is_in_skip(str_pos, skip_ranges) is True

        # 4. Return type arrow and annotation '-> int' must be skipped
        arrow_pos = source.find("->")
        assert _is_in_skip(arrow_pos, skip_ranges) is True
        ret_type_pos = source.find("int:\n")
        assert _is_in_skip(ret_type_pos, skip_ranges) is True

        # 5. Executable code 'return x + 1' must NOT be in skip ranges
        plus_pos = source.find("+ 1")
        assert _is_in_skip(plus_pos, skip_ranges) is False


