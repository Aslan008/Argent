class TestL2L3L7L9MutationExecutionAndSafety:
    def test_mutate_module_detects_killed_mutation_and_restores_file(self, tmp_path):
        # Create a tiny source file
        src_file = tmp_path / "calc_mod.py"
        src_code = "def is_positive(x):\n    return x > 0\n"
        src_file.write_text(src_code, encoding="utf-8")

        # Create a test that verifies is_positive
        test_file = tmp_path / "test_calc.py"
        test_file.write_text(
            "from calc_mod import is_positive\n"
            "def test_pos():\n"
            "    assert is_positive(5) is True\n"
            "    assert is_positive(-5) is False\n",
            encoding="utf-8"
        )

        with patch("tests.mutation_test.run_tests") as mock_run:
            # First mutation (e.g. > to <=) fails test
            mock_run.return_value = False

            killed, survived, total, details = mutate_module(str(src_file), [str(test_file)], max_mutations=5)
            assert total > 0
            assert killed > 0
            # Original file MUST be restored exactly
            assert src_file.read_text(encoding="utf-8") == src_code

    def test_file_restoration_guaranteed_even_on_unexpected_exception(self, tmp_path):
        src_file = tmp_path / "fragile_mod.py"
        src_code = "def check():\n    return True\n"
        src_file.write_text(src_code, encoding="utf-8")

        with patch("tests.mutation_test.run_tests", side_effect=RuntimeError("Subprocess crash")):
            try:
                mutate_module(str(src_file), ["fake_test.py"], max_mutations=1)
            except RuntimeError:
                pass

            # Even after an unhandled exception, source code must be restored
            assert src_file.read_text(encoding="utf-8") == src_code

    def test_run_tests_timeout_expired_treated_as_killed_mutation(self, tmp_path):
        src_file = tmp_path / "loop_mod.py"
        src_code = "def loop():\n    return 1\n"
        src_file.write_text(src_code, encoding="utf-8")

        with patch("tests.mutation_test.run_tests", side_effect=subprocess.TimeoutExpired(cmd="pytest", timeout=30)):
            killed, survived, total, details = mutate_module(str(src_file), ["test.py"], max_mutations=1)
            # Timeout means infinite loop was induced by mutation -> correctly killed
            assert killed == 1
            assert survived == 0
            assert src_file.read_text(encoding="utf-8") == src_code
