class TestL7UnicodeStreaming:
    def test_cyrillic_and_emoji_streamed_chunk_by_chunk(self):
        splitter = MarkdownStreamSplitter()
        parts = ["Привет, ", "мир! 🌍\n\n", "Второй ", "абзац с кодом:\n```python\nprint('Привет!')\n```\n\n"]
        committed = []
        for p in parts:
            c = splitter.feed(p)
            if c:
                committed.append(c)

        assert len(committed) == 2
        assert committed[0] == "Привет, мир! 🌍\n\n"
        assert "print('Привет!')" in committed[1]
        assert splitter.pending() == ""
