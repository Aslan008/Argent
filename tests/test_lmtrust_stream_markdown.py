# ============================================================================

class TestL2CodeFenceBoundaries:
    def test_code_fence_with_backticks_does_not_close_on_tildes(self):
        """A ``` fence cannot be closed by ~~~."""
        text = "```python\nx = 1\n~~~\n```\n\nAfter code.\n"
        boundary = _last_safe_boundary(text)
        # Safe boundary is at offset 25 (up to and including '\n\n' after closing ```)
        assert boundary == 25
        assert text[:boundary] == "```python\nx = 1\n~~~\n```\n\n"

    def test_unterminated_code_block_stays_pending(self):
        splitter = MarkdownStreamSplitter()
        # Feed unclosed code block
        chunk = splitter.feed("```python\ndef foo():\n    return 42\n")
        assert chunk == ""
        assert splitter.pending().startswith("```python")

        # Now feed closing fence and blank line
        chunk2 = splitter.feed("```\n\nNext text.")
        assert "```python" in chunk2
        assert "```\n\n" in chunk2
        assert splitter.pending() == "Next text."

    def test_quad_backtick_fence_requires_quad_or_more_to_close(self):
        """Code fence with 4 backticks ```` inside which 3 backticks ``` appear."""
        splitter = MarkdownStreamSplitter()
        feed1 = "````markdown\nHere is an example:\n```python\nprint(1)\n```\n````\n\n"
        chunk = splitter.feed(feed1)
        assert chunk == feed1
        assert splitter.pending() == ""


