class TestL4ReplaceInvariants:
    def test_replace_with_valid_prefix_updates_buffer(self):
        splitter = MarkdownStreamSplitter()
        # Feed paragraph 1
        p1 = splitter.feed("Paragraph 1.\n\n")
        assert p1 == "Paragraph 1.\n\n"

        # Stream continues with raw tool-call JSON in pending
        splitter.feed("Pending raw text that will be cleaned up.")
        assert splitter.pending() == "Pending raw text that will be cleaned up."

        # Model sanitizes stream and declares full text as "Paragraph 1.\n\nCleaned up text."
        splitter.replace("Paragraph 1.\n\nCleaned up text.")
        assert splitter.pending() == "Cleaned up text."

    def test_replace_with_divergent_prefix_drops_divergent_tail(self):
        splitter = MarkdownStreamSplitter()
        splitter.feed("Committed part.\n\n")
        splitter.feed("Pending garbage.")

        # Completely divergent replacement that doesn't start with "Committed part.\n\n"
        splitter.replace("Completely different text from scratch.")
        # Cannot un-print committed part, so pending becomes empty
        assert splitter.pending() == ""


