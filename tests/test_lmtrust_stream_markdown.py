# ============================================================================
# LAYER L1: Chunk Boundaries & Granularity
# ============================================================================

class TestL1ChunkGranularity:
    def test_single_character_feeding_accumulates_and_commits_on_blank_line(self):
        splitter = MarkdownStreamSplitter()
        text = "Hello world.\n\nSecond paragraph.\n"
        committed = []
        for ch in text:
            chunk = splitter.feed(ch)
            if chunk:
                committed.append(chunk)

        # Blank line triggers commit of the first paragraph
        assert len(committed) == 1
        assert committed[0] == "Hello world.\n\n"
        assert splitter.pending() == "Second paragraph.\n"

        tail = splitter.finalize()
        assert tail == "Second paragraph.\n"
        assert splitter.pending() == ""

    def test_empty_and_whitespace_only_chunks(self):
        splitter = MarkdownStreamSplitter()
        assert splitter.feed("") == ""
        # Single whitespace chunk without newline is committed if it matches blank line logic
        c = splitter.feed("First block.\n\n")
        assert c == "First block.\n\n"
        assert splitter.pending() == ""


