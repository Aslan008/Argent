class TestL2L4CorruptedBridgeRecoveryAndFallbacks:
    def test_list_pending_requests_skips_corrupted_json_files(self, tmp_path):
        bridge_dir = _get_bridge_dir(tmp_path)
        inbox = bridge_dir / "inbox"

        # Valid request
        src = tmp_path / "valid.py"
        src.write_text("pass", encoding="utf-8")
        req = create_test_request(src, base_dir=tmp_path)

        # Corrupted json in inbox
        corrupt_file = inbox / "req_corrupt.json"
        corrupt_file.write_text("{broken json", encoding="utf-8")

        pending = list_pending_requests(base_dir=tmp_path)
        assert len(pending) == 1
        assert pending[0]["id"] == req["id"]

    def test_get_test_response_handles_corrupted_outbox_file(self, tmp_path):
        bridge_dir = _get_bridge_dir(tmp_path)
        resp_file = bridge_dir / "outbox" / "req_broken_response.json"
        resp_file.write_text("{corrupt content", encoding="utf-8")

        assert get_test_response("req_broken", base_dir=tmp_path) is None
        assert get_test_response("nonexistent_req", base_dir=tmp_path) is None

    def test_apply_test_response_edge_cases(self, tmp_path):
        # Case 1: Response not found
        assert "not found in outbox" in apply_test_response("missing_req", base_dir=tmp_path)

        # Case 2: Empty test code
        submit_test_response("req_empty", test_code="   \n  ", base_dir=tmp_path)
        assert "contains empty test code" in apply_test_response("req_empty", base_dir=tmp_path)

        # Case 3: Missing inbox request file during apply -> fallback to module
        submit_test_response("req_no_inbox", test_code="def test_a(): pass", base_dir=tmp_path)
        msg = apply_test_response("req_no_inbox", base_dir=tmp_path)
        assert "test_lmtrust_module.py" in msg
        assert (tmp_path / "tests" / "test_lmtrust_module.py").exists()

        # Case 4: Custom target path
        custom_target = tmp_path / "custom" / "custom_test.py"
        apply_test_response("req_no_inbox", target_file=str(custom_target), base_dir=tmp_path)
        assert custom_target.exists()


