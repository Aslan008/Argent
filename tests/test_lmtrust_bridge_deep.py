class TestL7ExistingTestHarvester:
    def test_harvests_existing_test_files_into_request(self, tmp_path):
        src = tmp_path / "payment.py"
        src.write_text("def pay(): pass", encoding="utf-8")

        tests_dir = tmp_path / "tests"
        tests_dir.mkdir()
        t1 = tests_dir / "test_payment.py"
        t1.write_text("def test_old(): pass", encoding="utf-8")
        t2 = tests_dir / "test_lmtrust_payment.py"
        t2.write_text("def test_lmtrust_old(): pass", encoding="utf-8")

        req = create_test_request(src, base_dir=tmp_path)
        assert "=== test_payment.py ===" in req["existing_tests"]
        assert "def test_old(): pass" in req["existing_tests"]
        assert "=== test_lmtrust_payment.py ===" in req["existing_tests"]


