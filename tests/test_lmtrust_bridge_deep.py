class TestL1LayerNormalizationAndStemSanitization:
    def test_focus_layers_default_and_string_normalization(self, tmp_path):
        src = tmp_path / "mod.py"
        src.write_text("x = 1\n", encoding="utf-8")

        # Default layers when None
        req_def = create_test_request(src, focus_layers=None, base_dir=tmp_path)
        assert req_def["focus_layers"] == ["L1", "L2", "L3", "L4", "L4b", "L7", "L9"]

        # Comma-separated string with whitespace
        req_str = create_test_request(src, focus_layers=" L1 , L4b ,  L7 ", base_dir=tmp_path)
        assert req_str["focus_layers"] == ["L1", "L4b", "L7"]

        # Explicit list
        req_list = create_test_request(src, focus_layers=["L2", "L9"], base_dir=tmp_path)
        assert req_list["focus_layers"] == ["L2", "L9"]

    def test_clean_stem_sanitizes_special_characters_in_filename(self, tmp_path):
        src = tmp_path / "my tool.v1-2.beta.py"
        src.write_text("print('hello')", encoding="utf-8")

        req = create_test_request(src, base_dir=tmp_path)
        assert "my_tool_v1_2_beta" in req["id"] or "my_tool" in req["id"]
        assert " " not in req["id"]


