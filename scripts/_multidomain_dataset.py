def gen_department(n_target=600):
    out = []
    per = n_target // len(DEPT_CHOICES)
    for dept in DEPT_CHOICES:
        for i in range(per):
            t = rng.choice(DEPT_TEMPLATES[dept])
            text = (t.replace("{month}", rng.choice(["март", "апрель", "июнь", "август", "январь"]))
                     .replace("{amount}", str(rng.randrange(490, 4990, 10)))
                     .replace("{plan2}", rng.choice(["Start", "Pro"]))
                     .replace("{plan}", rng.choice(["Pro", "Business", "Enterprise"]))
                     .replace("{percent}", str(rng.choice([10, 15, 20, 25])))
                     .replace("{product}", rng.choice(PRODUCTS))
                     .replace("{error}", rng.choice(ERRORS))
                     .replace("{platform}", rng.choice(PLATFORMS))
                     .replace("{seats2}", str(rng.randrange(20, 200, 10)))
                     .replace("{seats}", str(rng.choice([10, 20, 50, 100])))
                     )
            state = envelope_support(text)
            out.append(LeethSample(state=state, question_type="choice", question=Q_DEPARTMENT,
                                   choices=DEPT_CHOICES, target_choice=dept))
    return out


